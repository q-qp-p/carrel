"""Operations used by Carrel, independent of the database drivers.

The state/queue SQLite database and graph extraction algorithms stay outside this
boundary. Payloads retain their source IDs, versions and locators verbatim.
"""
from __future__ import annotations

from typing import Any, Protocol


class ChunkStore(Protocol):
    def check(self) -> None: ...
    def image_payload(self, collection: str, point_id: str) -> dict: ...
    def table_head(self, collection: str, payload: dict, *, timeout: float | None = None) -> dict | None: ...
    def neighbors(self, collection: str, payload: dict, *, span: int, timeout: float | None = None) -> list[dict]: ...
    def metadata(self, collection: str, point_ids: list[str], *, timeout: float | None = None) -> dict: ...
    def exists(self, collection: str) -> bool: ...
    def ensure(self, collection: str, layout: Any, *, dry_run: bool = False) -> str: ...
    def validate(self, collection: str, layout: Any) -> dict[str, int]: ...
    def write(self, collection: str, point_ids: list[str], vectors: list[dict[str, list[float]]],
              payloads: list[dict[str, Any]], *, max_bytes: int) -> Any: ...
    def retire_previous(self, collection: str, *, kb_id: str, file_key: int, active_content_version: str) -> Any: ...
    def retire_stale(self, collection: str, *, kb_id: str, file_key: int, active_chunk_uids: set[str]) -> int: ...
    def payloads(self, collection: str, point_ids: list[str], *, timeout: float | None = None, active_only: bool = True) -> dict[str, dict]: ...
    def vectors(self, collection: str, point_ids: list[str]) -> dict[str, list[float]]: ...
    def active_count(self, collection: str) -> int: ...
    def vector_candidates(self, collection: str, vector: list[float], *, limit: int,
                          hints: dict | None = None, excluded: list[str] | None = None,
                          visual: bool = False, timeout: float | None = None) -> list[dict]: ...
    def context(self, collection: str, *, doc_id: str, chunk_from: int, chunk_to: int,
                content_version: str | None = None) -> list[dict]: ...
    def update_metadata(self, row: Any) -> None: ...
    def reactivate(self, row: Any, *, point_ids: list[str] | None = None) -> None: ...
    def version_count(self, row: Any) -> int: ...
    def deactivate(self, row: Any) -> None: ...


class KeywordStore(Protocol):
    def grep(self, source: Any, phrases: list[str], **options: Any) -> dict: ...
    def ensure(self, collections: list[str]) -> dict: ...
    def sync_document(self, collection: str, doc_id: str) -> dict: ...
    def delete(self, collection: str) -> dict: ...
    def candidates(self, question: str, collection: str, *, limit: int, identifiers: list[str] | None = None,
                   hints: dict | None = None, excluded: list[str] | None = None,
                   timeout: float | None = None) -> list[dict]: ...
    def profile(self, question: str, collections: list[str], *, timeout: float | None = None) -> dict: ...


class GraphStore(Protocol):
    def check(self) -> None: ...
    def vector_collections(self) -> set[str]: ...
    def vector_aliases(self) -> dict[str, str]: ...
    def alias_targets(self, collection: str) -> dict: ...
    def vector_exists(self, collection: str) -> bool: ...
    def vector_count(self, collection: str) -> int: ...
    def drop_aliases(self, collection: str, types: Any) -> Any: ...
    def collect_vectors(self, **options: Any) -> dict: ...
    def collect_versions(self, **options: Any) -> dict: ...
    def projection_matches(self, kb_id: str, version: str, expected: dict) -> bool: ...
    def deactivate(self, source: Any) -> dict: ...
    def document_dates(self, sources: list[dict], versions: dict, *, timeout: float | None = None) -> dict: ...
    def annotate_dates(self, sources: list[dict], scope: dict, *, timeout: float | None = None) -> Any: ...
    def read_originals(self, search_settings: Any, result: dict, scope: dict, hint: dict, until: float) -> Any: ...
    def stats(self, kb_id: str, *, timeout: float | None = None) -> Any: ...
    def neighborhoods(self, sources: dict, versions: dict, question: str, seeds: Any, **options: Any) -> Any: ...
    def locate_facts(self, collections: dict, specs: list[dict], sources: list[dict], *, timeout: float | None = None) -> Any: ...
    def corpus_payloads(self, collection: str, refs: list[dict]) -> Any: ...
    def write_vectors(self, embed: Any, **options: Any) -> dict: ...
    def import_version(self, **options: Any) -> dict: ...
    def activate_vectors(self, *, source_collection: str, graph_version: str) -> dict: ...
    def restore_vectors(self, previous: dict) -> bool: ...
    def activate(self, *, source: Any, graph_version: str) -> dict: ...
    def query(self, source: Any, question: str, **options: Any) -> dict: ...
    def neighbors(self, source: Any, **options: Any) -> dict: ...
    def entities(self, source: Any, **options: Any) -> dict: ...
    def facts(self, source: Any, **options: Any) -> dict: ...
    def pages(self, source: Any, **options: Any) -> dict: ...


class Storage(Protocol):
    def catalog(self, *, ttl: float, force: bool = False) -> list[dict]: ...
    def with_deadline(self, deadline: float) -> Storage: ...
    chunks: ChunkStore
    keywords: KeywordStore
    graph: GraphStore
